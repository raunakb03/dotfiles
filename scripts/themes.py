#!/usr/bin/env python3
"""Make other apps follow the wallpaper colours.

    themes.py            read ~/.local/state/myshell/scheme.json and write every app's theme

Called by set-wallpaper.py after it writes a new scheme; run it by hand after editing this file.
Writes:
    ~/.local/state/myshell/theme/kitty.conf     included from ~/.config/kitty/kitty.conf
    ~/.config/btop/themes/myshell.theme         selected in ~/.config/btop/btop.conf
    ~/.config/gtk-4.0/gtk.css                   GTK 4 / libadwaita apps (Nautilus, …)
    ~/.config/gtk-3.0/gtk.css                   GTK 3 apps
"""

import json
import os
import subprocess
from pathlib import Path

from materialyoucolor.blend import Blend
from materialyoucolor.hct import Hct

HOME = Path.home()
CONFIG = Path(os.environ.get("XDG_CONFIG_HOME", HOME / ".config"))
STATE_DIR = Path(os.environ.get("XDG_STATE_HOME", HOME / ".local/state")) / "myshell"

GENERATED = "Generated by my-first-shell/scripts/themes.py from the wallpaper. Don't edit: it's overwritten on every wallpaper change."


def write_atomically(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text)
    tmp.replace(path)


# ---------------------------------------------------------------------------------------------
# The 16 terminal colours
# ---------------------------------------------------------------------------------------------

# The classic hues. Each is "harmonized": its hue is turned a little (at most 15°) towards the
# wallpaper's main colour, so red stays recognisably red but sits well with the palette.
ANSI_BASE = {
    "red": 0xFFE5484D,
    "green": 0xFF46A758,
    "yellow": 0xFFE2B714,
    "blue": 0xFF3E7BFA,
    "magenta": 0xFFC85BD6,
    "cyan": 0xFF12A5B0,
}


def tone(argb: int, chroma: float, tone_value: float) -> str:
    """The same hue at a chosen colourfulness (chroma) and lightness (tone, 0-100)."""
    hct = Hct.from_int(argb)
    out = Hct.from_hct(hct.hue, min(chroma, hct.chroma), tone_value).to_int()
    return f"#{out & 0xFFFFFF:06x}"


def terminal_colours(source: int, c: dict[str, str]) -> list[str]:
    """color0-15: normal colours fairly light, bright ones lighter (readable on a dark background)."""
    hues = {name: Blend.harmonize(argb, source) for name, argb in ANSI_BASE.items()}
    # (chroma, tone) per colour: yellow only looks yellow when it's light, and red turns pink
    # when it's light, so they get their own values
    normal_ct = {"red": (75, 62), "yellow": (65, 82)}
    bright_ct = {"red": (60, 74), "yellow": (55, 90)}
    names = ("red", "green", "yellow", "blue", "magenta", "cyan")
    normal = [tone(hues[n], *normal_ct.get(n, (60, 70))) for n in names]
    bright = [tone(hues[n], *bright_ct.get(n, (50, 82))) for n in names]
    return (
        [f"#{c['surfaceContainerHighest']}", *normal, f"#{c['onSurfaceVariant']}"]
        + [f"#{c['outline']}", *bright, f"#{c['onSurface']}"]
    )


# ---------------------------------------------------------------------------------------------
# kitty
# ---------------------------------------------------------------------------------------------

def kitty(c: dict[str, str], term: list[str]) -> None:
    lines = [f"# {GENERATED}",
             f"background #{c['surface']}",
             f"foreground #{c['onSurface']}",
             f"cursor #{c['primary']}",
             f"cursor_text_color #{c['onPrimary']}",
             f"selection_background #{c['primaryContainer']}",
             f"selection_foreground #{c['onPrimaryContainer']}",
             f"url_color #{c['tertiary']}",
             f"active_border_color #{c['primary']}",
             f"inactive_border_color #{c['outlineVariant']}",
             f"tab_bar_background #{c['surfaceContainer']}",
             f"active_tab_background #{c['primary']}",
             f"active_tab_foreground #{c['onPrimary']}",
             f"inactive_tab_background #{c['surfaceContainerHigh']}",
             f"inactive_tab_foreground #{c['onSurfaceVariant']}",
             f"mark1_background #{c['tertiary']}",
             f"mark1_foreground #{c['onTertiary']}"]
    lines += [f"color{i} {colour}" for i, colour in enumerate(term)]
    write_atomically(STATE_DIR / "theme/kitty.conf", "\n".join(lines) + "\n")

    # kitty re-reads its whole config (including our include) on SIGUSR1: running terminals
    # change colour immediately
    subprocess.run(["pkill", "-USR1", "-x", "kitty"], check=False)


# ---------------------------------------------------------------------------------------------
# btop
# ---------------------------------------------------------------------------------------------

def btop(c: dict[str, str], term: list[str]) -> None:
    red, green, yellow, blue, magenta, cyan = term[1:7]
    t = {
        "main_bg": f"#{c['surface']}",
        "main_fg": f"#{c['onSurface']}",
        "title": f"#{c['onSurface']}",
        "hi_fg": f"#{c['primary']}",               # the highlighted letter of each shortcut
        "selected_bg": f"#{c['primaryContainer']}",
        "selected_fg": f"#{c['onPrimaryContainer']}",
        "inactive_fg": f"#{c['outline']}",
        "graph_text": f"#{c['onSurfaceVariant']}",
        "meter_bg": f"#{c['surfaceContainerHighest']}",
        "proc_misc": f"#{c['secondary']}",
        "cpu_box": f"#{c['primary']}",
        "mem_box": f"#{c['secondary']}",
        "net_box": f"#{c['tertiary']}",
        "proc_box": f"#{c['outline']}",
        "div_line": f"#{c['outlineVariant']}",
        # Gradients: low → medium → high
        "temp_start": green, "temp_mid": yellow, "temp_end": red,
        "cpu_start": f"#{c['primary']}", "cpu_mid": f"#{c['tertiary']}", "cpu_end": red,
        "free_start": green, "free_mid": "", "free_end": green,
        "cached_start": blue, "cached_mid": "", "cached_end": blue,
        "available_start": cyan, "available_mid": "", "available_end": cyan,
        "used_start": yellow, "used_mid": "", "used_end": red,
        "download_start": blue, "download_mid": cyan, "download_end": green,
        "upload_start": magenta, "upload_mid": red, "upload_end": yellow,
        "process_start": f"#{c['primary']}", "process_mid": f"#{c['tertiary']}", "process_end": red,
    }
    text = f"# {GENERATED}\n" + "".join(f'theme[{k}]="{v}"\n' for k, v in t.items())
    theme_file = CONFIG / "btop/themes/myshell.theme"
    write_atomically(theme_file, text)

    # Select it in btop.conf (btop writes the rest of its settings there itself on exit)
    conf = CONFIG / "btop/btop.conf"
    line = f'color_theme = "{theme_file}"'
    if conf.exists():
        old = conf.read_text().splitlines()
        new = [line if l.startswith("color_theme") else l for l in old]
        if line not in new:
            new.append(line)
        if new != old:
            write_atomically(conf, "\n".join(new) + "\n")
    else:
        write_atomically(conf, f"# btop adds its other settings here when it exits\n{line}\n")


# ---------------------------------------------------------------------------------------------
# GTK
# ---------------------------------------------------------------------------------------------

def gtk(c: dict[str, str]) -> None:
    # libadwaita's named colours (GTK 4). The adw-gtk3 theme uses the same names for GTK 3;
    # plain GTK 3 Adwaita only follows the theme_* ones below.
    adw = {
        "accent_color": c["primary"], "accent_bg_color": c["primary"], "accent_fg_color": c["onPrimary"],
        "destructive_color": c["error"], "destructive_bg_color": c["errorContainer"], "destructive_fg_color": c["onErrorContainer"],
        "window_bg_color": c["surface"], "window_fg_color": c["onSurface"],
        "view_bg_color": c["surfaceContainerLow"], "view_fg_color": c["onSurface"],
        "headerbar_bg_color": c["surfaceContainer"], "headerbar_fg_color": c["onSurface"],
        "headerbar_backdrop_color": c["surface"],
        "sidebar_bg_color": c["surfaceContainer"], "sidebar_fg_color": c["onSurface"],
        "sidebar_backdrop_color": c["surfaceContainerLow"],
        "secondary_sidebar_bg_color": c["surfaceContainerLow"], "secondary_sidebar_fg_color": c["onSurface"],
        "card_bg_color": c["surfaceContainerHigh"], "card_fg_color": c["onSurface"],
        "dialog_bg_color": c["surfaceContainerHigh"], "dialog_fg_color": c["onSurface"],
        "popover_bg_color": c["surfaceContainerHigh"], "popover_fg_color": c["onSurface"],
        "thumbnail_bg_color": c["surfaceContainerHigh"], "thumbnail_fg_color": c["onSurface"],
        # GTK 3 Adwaita's names
        "theme_bg_color": c["surface"], "theme_fg_color": c["onSurface"],
        "theme_base_color": c["surfaceContainerLow"], "theme_text_color": c["onSurface"],
        "theme_selected_bg_color": c["primary"], "theme_selected_fg_color": c["onPrimary"],
    }
    css = f"/* {GENERATED} */\n" + "".join(f"@define-color {k} #{v};\n" for k, v in adw.items())
    for version in ("gtk-3.0", "gtk-4.0"):
        write_atomically(CONFIG / version / "gtk.css", css)


def main() -> None:
    scheme = json.loads((STATE_DIR / "scheme.json").read_text())
    colours = scheme["colours"]
    source = 0xFF000000 | int(scheme["source"], 16)

    term = terminal_colours(source, colours)
    kitty(colours, term)
    btop(colours, term)
    gtk(colours)
    print("themes: kitty, btop, gtk")


if __name__ == "__main__":
    main()
